create or replace function public.validate_quickbooks_studio_assignment()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if not exists (
    select 1 from public.studios studio
    where studio.id = new.studio_id
      and studio.organization_id = new.organization_id
  ) then
    raise exception 'QuickBooks studio assignment crosses organization boundary';
  end if;
  return new;
end;
$$;

