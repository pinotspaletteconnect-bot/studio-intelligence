create or replace function public.assign_quickbooks_connection_to_studio(
  p_organization_id bigint,
  p_connection_id bigint,
  p_studio_id bigint,
  p_effective_from date default current_date
) returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  assignment_id bigint;
begin
  if not exists (
    select 1 from public.quickbooks_connections connection
    where connection.id = p_connection_id
      and connection.organization_id = p_organization_id
      and connection.is_active = true
  ) then
    raise exception 'QuickBooks connection not found';
  end if;
  if not exists (
    select 1 from public.studios studio
    where studio.id = p_studio_id
      and studio.organization_id = p_organization_id
      and studio.active = true
  ) then
    raise exception 'Studio not found';
  end if;

  update public.quickbooks_studio_assignments
  set is_active = false,
      effective_to = greatest(p_effective_from - 1, effective_from),
      updated_at = now()
  where studio_id = p_studio_id
    and is_active = true
    and effective_to is null;

  insert into public.quickbooks_studio_assignments (
    organization_id, connection_id, studio_id, effective_from
  ) values (
    p_organization_id, p_connection_id, p_studio_id, p_effective_from
  )
  returning id into assignment_id;

  return assignment_id;
end;
$$;

create or replace view public.quickbooks_collection_targets as
select
  connection.organization_id,
  connection.id as connection_id,
  connection.connection_name,
  connection.realm_id,
  connection.company_name,
  connection.connection_status,
  connection.write_enabled,
  assignment.studio_id,
  studio.brand_id,
  studio.studio_code,
  studio.studio_name,
  studio.timezone,
  assignment.effective_from,
  assignment.effective_to
from public.quickbooks_connections connection
left join public.quickbooks_studio_assignments assignment
  on assignment.connection_id = connection.id
 and assignment.organization_id = connection.organization_id
 and assignment.is_active = true
 and assignment.effective_to is null
left join public.studios studio
  on studio.id = assignment.studio_id
 and studio.organization_id = connection.organization_id
 and studio.active = true
where connection.is_active = true;

