create or replace function public.create_quickbooks_oauth_connection_with_secret(
  p_organization_id bigint,
  p_connection_name text,
  p_realm_id text,
  p_oauth_credentials jsonb,
  p_granted_scopes text[] default array[]::text[]
) returns bigint
language plpgsql
security definer
set search_path = public, vault, pg_temp
as $$
declare
  connection_id bigint;
  existing_secret_reference text;
  vault_secret_id uuid;
begin
  if char_length(trim(p_connection_name)) not between 2 and 120 then
    raise exception 'Invalid QuickBooks connection name';
  end if;
  if trim(p_realm_id) !~ '^[0-9]{1,40}$' then
    raise exception 'Invalid QuickBooks realm ID';
  end if;
  if jsonb_typeof(p_oauth_credentials) <> 'object'
    or nullif(p_oauth_credentials ->> 'refresh_token', '') is null
  then
    raise exception 'Invalid QuickBooks OAuth credentials';
  end if;
  if not exists (select 1 from public.organizations where id = p_organization_id) then
    raise exception 'Organization not found';
  end if;

  select id, secret_reference
    into connection_id, existing_secret_reference
  from public.quickbooks_connections
  where organization_id = p_organization_id
    and realm_id = trim(p_realm_id)
  for update;

  if connection_id is null then
    insert into public.quickbooks_connections (
      organization_id, connection_name, realm_id, secret_reference,
      granted_scopes, connection_status, write_enabled, write_pause_reason
    ) values (
      p_organization_id, trim(p_connection_name), trim(p_realm_id),
      'pending:' || gen_random_uuid()::text, coalesce(p_granted_scopes, array[]::text[]),
      'connected', false, 'Phase 1 read-only foundation'
    ) returning id into connection_id;

    select vault.create_secret(
      p_oauth_credentials::text,
      'quickbooks-oauth-connection-' || connection_id::text,
      'Studio Intelligence QuickBooks Online OAuth refresh credential'
    ) into vault_secret_id;
  else
    if existing_secret_reference !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' then
      raise exception 'QuickBooks Vault secret reference is invalid';
    end if;
    vault_secret_id := existing_secret_reference::uuid;
    perform vault.update_secret(
      vault_secret_id,
      p_oauth_credentials::text,
      'quickbooks-oauth-connection-' || connection_id::text,
      'Studio Intelligence QuickBooks Online OAuth refresh credential'
    );
  end if;

  update public.quickbooks_connections
  set connection_name = trim(p_connection_name),
      secret_reference = vault_secret_id::text,
      granted_scopes = coalesce(p_granted_scopes, array[]::text[]),
      connection_status = 'connected',
      write_enabled = false,
      write_pause_reason = 'Phase 1 read-only foundation',
      is_active = true,
      last_validated_at = now(),
      updated_at = now()
  where id = connection_id;

  return connection_id;
end;
$$;

create or replace function public.get_quickbooks_connection_secret(p_connection_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public, vault, pg_temp
as $$
declare
  decrypted_value text;
begin
  select secret.decrypted_secret into decrypted_value
  from public.quickbooks_connections connection
  join vault.decrypted_secrets secret
    on secret.id = case
      when connection.secret_provider = 'supabase_vault'
       and connection.secret_reference ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
        then connection.secret_reference::uuid
      else null
    end
  where connection.id = p_connection_id
    and connection.is_active = true
    and connection.connection_status <> 'disabled';

  if decrypted_value is null then
    raise exception 'QuickBooks connection secret not found';
  end if;
  return decrypted_value::jsonb;
end;
$$;

