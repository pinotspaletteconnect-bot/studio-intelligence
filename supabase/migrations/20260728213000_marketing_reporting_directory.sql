drop view public.ga4_source_medium_performance;

create view public.ga4_source_medium_performance
with (security_invoker = true)
as
select
  fact.organization_id,
  fact.brand_id,
  fact.studio_id,
  fact.attribution_date as report_date,
  fact.source,
  fact.medium,
  coalesce(directory.display_name, fallback.display_name) as display_name,
  coalesce(directory.vendor, mapping.vendor, fallback.vendor) as vendor,
  coalesce(directory.marketing_type, mapping.marketing_type, fallback.marketing_type) as marketing_type,
  coalesce(directory.traffic_category, mapping.traffic_category, fallback.traffic_category) as traffic_category,
  coalesce(directory.reporting_group, fallback.reporting_group) as reporting_group,
  coalesce(directory.visibility, fallback.visibility) as visibility,
  coalesce(directory.group_label, fallback.group_label) as group_label,
  coalesce(directory.sort_order, fallback.sort_order) as sort_order,
  fact.users as total_users,
  fact.new_users,
  fact.sessions,
  fact.engaged_sessions,
  fact.page_views,
  fact.engagement_rate,
  fact.average_session_duration,
  fact.key_events,
  fact.session_key_event_rate,
  fact.revenue as total_revenue
from public.marketing_attribution_daily fact
left join public.marketing_source_mapping mapping
  on mapping.active is true
 and lower(mapping.source) = lower(fact.source)
 and lower(mapping.medium) = lower(fact.medium)
left join lateral (
  select configured.*
  from public.marketing_reporting_sources configured
  where configured.active is true
    and lower(configured.source) = lower(fact.source)
    and lower(configured.medium) = lower(fact.medium)
    and (configured.organization_id is null or configured.organization_id = fact.organization_id)
    and (configured.brand_id is null or configured.brand_id = fact.brand_id)
    and (configured.studio_id is null or configured.studio_id = fact.studio_id)
  order by
    (configured.studio_id is not null) desc,
    (configured.brand_id is not null) desc,
    (configured.organization_id is not null) desc
  limit 1
) directory on true
cross join lateral (
  select
    case
      when lower(fact.medium) ~ '(^|_)(cpc|ppc|paid|paid_social|display|affiliate|cpv|cpm)($|_)'
        then coalesce(mapping.vendor, initcap(fact.source))
      when lower(fact.source) in ('facebook', 'facebook.com', 'm.facebook.com', 'l.facebook.com', 'lm.facebook.com')
        then 'Facebook Organic'
      when lower(fact.source) in ('instagram', 'instagram.com', 'l.instagram.com', 'ig')
        then 'Instagram Organic'
      else coalesce(mapping.description, mapping.vendor, initcap(fact.source))
    end as display_name,
    coalesce(mapping.vendor, initcap(fact.source), 'Unmapped') as vendor,
    case
      when lower(fact.medium) ~ '(^|_)(cpc|ppc|paid|paid_social|display|affiliate|cpv|cpm)($|_)'
        then 'Paid'
      when lower(fact.medium) in ('social', 'social-organic', 'organic_social')
        or lower(fact.source) ~ '(facebook|instagram|pinterest|linkedin|tiktok|youtube)'
        then 'Organic'
      when lower(fact.medium) = 'organic' then 'Organic'
      when lower(fact.medium) = 'referral' then 'Referral'
      else coalesce(mapping.marketing_type, 'Unmapped')
    end as marketing_type,
    case
      when lower(fact.medium) ~ '(^|_)(cpc|ppc|paid|paid_social|display|affiliate|cpv|cpm)($|_)'
        then coalesce(mapping.traffic_category, 'Paid')
      when lower(fact.medium) in ('social', 'social-organic', 'organic_social')
        or lower(fact.source) ~ '(facebook|instagram|pinterest|linkedin|tiktok|youtube)'
        then 'Organic Social'
      when lower(fact.medium) = 'organic' then 'Organic Search'
      when lower(fact.medium) = 'referral' then 'Referral'
      else coalesce(mapping.traffic_category, 'Unmapped')
    end as traffic_category,
    case
      when lower(fact.medium) ~ '(^|_)(cpc|ppc|paid|paid_social|display|affiliate|cpv|cpm)($|_)'
        then 'Paid'
      when lower(fact.medium) in ('social', 'social-organic', 'organic_social')
        or lower(fact.source) ~ '(facebook|instagram|pinterest|linkedin|tiktok|youtube)'
        then 'Organic Social'
      when lower(fact.source) = 'google' and lower(fact.medium) = 'organic'
        then 'Organic Search'
      when lower(fact.source) = '(direct)' and lower(fact.medium) = '(none)'
        then 'Direct'
      when lower(fact.medium) = 'referral' then 'Other Referrals'
      else 'Other Traffic'
    end as reporting_group,
    case
      when lower(fact.medium) ~ '(^|_)(cpc|ppc|paid|paid_social|display|affiliate|cpv|cpm)($|_)'
        or lower(fact.medium) in ('social', 'social-organic', 'organic_social')
        or lower(fact.source) ~ '(facebook|instagram|pinterest|linkedin|tiktok|youtube)'
        or (lower(fact.source) = 'google' and lower(fact.medium) = 'organic')
        or (lower(fact.source) = '(direct)' and lower(fact.medium) = '(none)')
        then 'Featured'
      when lower(fact.medium) = 'referral' then 'Grouped'
      else 'Hidden'
    end as visibility,
    case when lower(fact.medium) = 'referral' then 'Other Referrals' end as group_label,
    case
      when lower(fact.medium) ~ '(^|_)(cpc|ppc|paid|paid_social|display|affiliate|cpv|cpm)($|_)' then 200
      when lower(fact.medium) in ('social', 'social-organic', 'organic_social')
        or lower(fact.source) ~ '(facebook|instagram|pinterest|linkedin|tiktok|youtube)' then 300
      when lower(fact.medium) = 'referral' then 800
      else 900
    end as sort_order
) fallback;

revoke all on table public.ga4_source_medium_performance from anon, authenticated;
