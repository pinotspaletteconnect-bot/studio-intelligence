-- Curated source directory for scalable, multi-studio marketing reporting.
-- Raw GA4 source/medium facts remain unchanged.

begin;

create table if not exists public.marketing_reporting_sources (
  id bigint generated by default as identity primary key,
  organization_id bigint references public.organizations(id) on delete cascade,
  brand_id bigint references public.brands(id) on delete cascade,
  studio_id bigint references public.studios(id) on delete cascade,
  source text not null,
  medium text not null,
  display_name text not null,
  vendor text not null,
  marketing_type text not null,
  traffic_category text not null,
  reporting_group text not null,
  visibility text not null default 'Featured'
    check (visibility in ('Featured', 'Grouped', 'Hidden')),
  group_label text,
  sort_order integer not null default 500,
  active boolean not null default true,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (studio_id is null or brand_id is not null)
    and (brand_id is null or organization_id is not null)
  ),
  check (visibility <> 'Grouped' or group_label is not null)
);

create unique index if not exists marketing_reporting_sources_scope_key
  on public.marketing_reporting_sources (
    coalesce(organization_id, 0),
    coalesce(brand_id, 0),
    coalesce(studio_id, 0),
    lower(source),
    lower(medium)
  );

create index if not exists marketing_reporting_sources_lookup_idx
  on public.marketing_reporting_sources (
    lower(source),
    lower(medium),
    active,
    organization_id,
    brand_id,
    studio_id
  );

alter table public.marketing_reporting_sources enable row level security;
revoke all on table public.marketing_reporting_sources from anon, authenticated;
grant select, insert, update, delete on table public.marketing_reporting_sources to service_role;
grant usage, select on sequence public.marketing_reporting_sources_id_seq to service_role;

