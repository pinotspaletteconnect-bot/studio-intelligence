-- Privacy-safe, reciprocal benchmark participation and the first benchmark:
-- paid CPC. Only service-role application code can read or change consent.

begin;

create table if not exists public.benchmark_participation_settings (
  organization_id bigint primary key
    references public.organizations(id) on delete cascade,
  opted_in boolean not null default false,
  consent_version text not null default '1.0',
  consented_by uuid,
  consented_at timestamptz,
  withdrawn_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint benchmark_participation_consent_dates check (
    (opted_in and consented_at is not null and withdrawn_at is null)
    or
    (not opted_in)
  )
);

create table if not exists public.benchmark_participation_audit (
  id bigint generated by default as identity primary key,
  organization_id bigint not null
    references public.organizations(id) on delete cascade,
  opted_in boolean not null,
  consent_version text not null,
  changed_by uuid,
  changed_at timestamptz not null default now()
);

create index if not exists benchmark_participation_audit_org_date_idx
  on public.benchmark_participation_audit (organization_id, changed_at desc);

create or replace function public.audit_benchmark_participation()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' or old.opted_in is distinct from new.opted_in then
    insert into public.benchmark_participation_audit (
      organization_id,
      opted_in,
      consent_version,
      changed_by
    )
    values (
      new.organization_id,
      new.opted_in,
      new.consent_version,
      new.consented_by
    );
  end if;
  return new;
end;
$$;

drop trigger if exists benchmark_participation_audit_trigger
  on public.benchmark_participation_settings;
create trigger benchmark_participation_audit_trigger
after insert or update of opted_in
on public.benchmark_participation_settings
for each row execute function public.audit_benchmark_participation();

alter table public.benchmark_participation_settings enable row level security;
alter table public.benchmark_participation_audit enable row level security;

revoke all on table public.benchmark_participation_settings
  from anon, authenticated;
revoke all on table public.benchmark_participation_audit
  from anon, authenticated;
grant select, insert, update on table public.benchmark_participation_settings
  to service_role;
grant select on table public.benchmark_participation_audit to service_role;
grant usage, select on sequence public.benchmark_participation_audit_id_seq
  to service_role;

create or replace function public.get_paid_cpc_benchmark(
  requested_studio_id bigint,
  period_start date,
  period_end date
)
returns table (
  participating boolean,
  available boolean,
  cohort_studios bigint,
  cohort_organizations bigint,
  median_value numeric,
  mean_value numeric
)
language sql
stable
security definer
set search_path = public
as $$
  with requester as (
    select
      s.organization_id,
      coalesce(p.opted_in, false) as participating
    from public.studios s
    left join public.benchmark_participation_settings p
      on p.organization_id = s.organization_id
    where s.id = requested_studio_id
  ),
  participating_studios as (
    select s.id as studio_id, s.organization_id
    from public.studios s
    join public.benchmark_participation_settings p
      on p.organization_id = s.organization_id
     and p.opted_in = true
    where s.active = true
  ),
  summary_metrics as (
    select
      m.studio_id,
      sum(coalesce(m.meta_spend, 0)) as meta_spend,
      sum(coalesce(m.meta_clicks, 0) + coalesce(m.eulerity_clicks, 0))
        as paid_clicks
    from public.marketing_daily_summary m
    join participating_studios ps on ps.studio_id = m.studio_id
    where m.report_date between period_start and period_end
    group by m.studio_id
  ),
  eulerity_spend as (
    select
      e.studio_id,
      sum(coalesce(e.spend_total, 0)) as spend
    from public.eulerity_daily_metrics e
    join participating_studios ps on ps.studio_id = e.studio_id
    where e.report_date between period_start and period_end
    group by e.studio_id
  ),
  studio_values as (
    select
      ps.studio_id,
      ps.organization_id,
      (
        coalesce(sm.meta_spend, 0) + coalesce(es.spend, 0)
      ) / nullif(coalesce(sm.paid_clicks, 0), 0) as value
    from participating_studios ps
    left join summary_metrics sm on sm.studio_id = ps.studio_id
    left join eulerity_spend es on es.studio_id = ps.studio_id
  ),
  cohort as (
    select *
    from studio_values
    where value is not null and value >= 0
  ),
  aggregate_result as (
    select
      count(*)::bigint as studio_count,
      count(distinct organization_id)::bigint as organization_count,
      percentile_cont(0.5) within group (order by value)::numeric as median,
      avg(value)::numeric as mean
    from cohort
  )
  select
    coalesce(r.participating, false),
    coalesce(r.participating, false)
      and a.studio_count >= 10
      and a.organization_count >= 3,
    case when r.participating then a.studio_count else null end,
    case when r.participating then a.organization_count else null end,
    case
      when r.participating
       and a.studio_count >= 10
       and a.organization_count >= 3
      then a.median
      else null
    end,
    case
      when r.participating
       and a.studio_count >= 10
       and a.organization_count >= 3
      then a.mean
      else null
    end
  from aggregate_result a
  left join requester r on true;
$$;

revoke all on function public.get_paid_cpc_benchmark(bigint, date, date)
  from public, anon, authenticated;
grant execute on function public.get_paid_cpc_benchmark(bigint, date, date)
  to service_role;

comment on table public.benchmark_participation_settings is
  'Organization-level reciprocal benchmark consent. Defaults to opted out.';
comment on function public.get_paid_cpc_benchmark(bigint, date, date) is
  'Returns paid CPC median/mean only to participating organizations and only for cohorts of at least 10 studios across 3 organizations.';

commit;
